// Automatically ensure all category words and multi-meaning words are in WORDS_10K_DATABASE
(function mergeVocabDatabase() {
  if (typeof window.WORDS_10K_DATABASE === 'undefined') {
    window.WORDS_10K_DATABASE = [];
  }

  const existingMap = new Map();
  window.WORDS_10K_DATABASE.forEach(item => {
    if (item && item.word) {
      existingMap.set(item.word.toLowerCase(), item);
    }
  });

  // 1. Merge Multi-meaning words
  Object.keys(window.MULTI_MEANING_WORDS).forEach(key => {
    const mm = window.MULTI_MEANING_WORDS[key];
    if (existingMap.has(key)) {
      const item = existingMap.get(key);
      item.hindi = mm.primaryHindi;
      item.multiMeaning = true;
    } else {
      const newItem = { word: mm.word, hindi: mm.primaryHindi, multiMeaning: true };
      window.WORDS_10K_DATABASE.push(newItem);
      existingMap.set(key, newItem);
    }
  });

  // 2. Merge all Essential Category words
  Object.keys(window.ESSENTIAL_CATEGORIES).forEach(catKey => {
    const cat = window.ESSENTIAL_CATEGORIES[catKey];
    if (cat && Array.isArray(cat.words)) {
      cat.words.forEach(cw => {
        const wLow = cw.word.toLowerCase();
        if (existingMap.has(wLow)) {
          const item = existingMap.get(wLow);
          item.hindi = cw.hindi;
          item.category = catKey;
        } else {
          const newItem = { word: cw.word, hindi: cw.hindi, category: catKey };
          window.WORDS_10K_DATABASE.push(newItem);
          existingMap.set(wLow, newItem);
        }
      });
    }
  });

  console.log("vocab_categories.js loaded: Verified", Object.keys(window.MULTI_MEANING_WORDS).length, "multi-meaning words and", Object.keys(window.ESSENTIAL_CATEGORIES).length, "essential categories!");
})();
